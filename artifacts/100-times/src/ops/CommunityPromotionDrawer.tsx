import { Link } from 'wouter';
import { Check, Send, XCircle } from 'lucide-react';
import { type CommunityPromotionOpportunity, usePromotionOpportunityAction, usePublishPromotionOpportunity } from './api';
import { Badge, Btn, DL, Drawer, ErrorState, NA, Notice, Section, fmtDateTime, val } from './ui';

const STATUS_TONE: Record<string, 'neutral' | 'good' | 'warn' | 'danger' | 'accent' | 'info'> = {
  pending: 'accent', approved: 'warn', rejected: 'danger', scheduled: 'warn',
  ready_for_manual_publishing: 'warn', published: 'good',
};

export function CommunityPromotionDrawer({ opportunity: op, onClose }: { opportunity: CommunityPromotionOpportunity | null; onClose: () => void }) {
  const action = usePromotionOpportunityAction();
  const publish = usePublishPromotionOpportunity();

  if (!op) return null;
  const canApprove = op.approvalStatus === 'pending';
  const canReject = op.approvalStatus === 'pending' || op.approvalStatus === 'approved';
  const canPublish = op.approvalStatus === 'approved' || op.approvalStatus === 'ready_for_manual_publishing';
  const isPublished = op.approvalStatus === 'published';

  const footer = (
    <div className="space-y-3">
      {action.isError && <ErrorState error={action.error} title="Action failed" />}
      {publish.isError && <ErrorState error={publish.error} title="Publish failed" />}
      <div className="flex flex-wrap items-center gap-2">
        {canApprove && <Btn variant="primary" loading={action.isPending} onClick={() => action.mutate({ id: op.id, action: 'approve' })}><Check size={13} /> Approve</Btn>}
        {canPublish && <Btn variant="primary" loading={publish.isPending} onClick={() => publish.mutate(op.id)}><Send size={13} /> Publish post</Btn>}
        {canReject && <Btn onClick={() => action.mutate({ id: op.id, action: 'reject' })} loading={action.isPending}><XCircle size={13} /> Reject</Btn>}
      </div>
      {canApprove && <p className="text-[11px] text-muted-foreground">Approving does not publish. After approval, a separate "Publish post" step actually sends it — nothing goes out without both.</p>}
      {op.targetCommunity && !op.targetCommunity.connected && !isPublished && (
        <Notice tone="warn">This community isn't connected yet (no known chat/channel id for the bot). Publishing will fail honestly until it's connected — set its platform reference from the Community Discovery page first.</Notice>
      )}
    </div>
  );

  return (
    <Drawer open onClose={onClose} kicker={`Community promotion #${op.id}`} title={op.contentPayload?.subject ?? op.promotedEvent?.title ?? 'Draft'} footer={footer} width="max-w-3xl">
      <div className="flex flex-wrap items-center gap-2">
        <Badge tone={STATUS_TONE[op.approvalStatus] ?? 'neutral'}>{op.approvalStatus.replace(/_/g, ' ')}</Badge>
        <Badge tone={op.contentGeneratedBy === 'ai' ? 'info' : 'neutral'}>{op.contentGeneratedBy === 'ai' ? 'AI generated' : 'Template fallback'}</Badge>
      </div>

      <Section title="Event" aside={op.promotedEvent && <Link href={`/admin/discovery/events`} className="font-mono-face text-[10px] uppercase tracking-wider text-accent hover:underline">All events →</Link>}>
        <DL rows={[
          ['Event', val(op.promotedEvent?.title)],
          ['Relevance score', `${op.relevanceScore} / 100`],
          ['Why this match', op.matchExplanation ?? NA],
        ]} />
      </Section>

      <Section title="Target community">
        <DL rows={[
          ['Community', val(op.targetCommunity?.name)],
          ['Platform', val(op.targetCommunity?.platform)],
          ['Connected', op.targetCommunity ? (op.targetCommunity.connected ? 'Yes' : 'Not yet — bot has no known destination id') : NA],
        ]} />
      </Section>

      <Section title="Post" aside={<span className="font-mono-face text-[10px] uppercase tracking-wider text-muted-foreground">{isPublished ? 'Exact post published' : 'Exact draft awaiting approval'}</span>}>
        <div className="rounded-xl border border-foreground/10 bg-background p-5 text-sm">
          {op.contentPayload?.subject && <p className="border-b border-foreground/10 pb-3 font-mono-face text-[11px] text-muted-foreground"><span className="inline-block w-16">Subject</span><span className="text-foreground">{op.contentPayload.subject}</span></p>}
          <p className="mt-4 whitespace-pre-wrap leading-relaxed text-foreground/90">{op.generatedResponse}</p>
        </div>
        <DL rows={[
          ['Generated by', op.contentGeneratedBy === 'ai' ? 'Promotion agent (AI model)' : 'Promotion agent (deterministic template)'],
          ['Generated at', fmtDateTime(op.createdAt)],
          ['Published at', fmtDateTime(op.publishedAt)],
          ['Published URL', op.publishedUrl ? <a href={op.publishedUrl} target="_blank" rel="noreferrer" className="text-accent hover:underline">{op.publishedUrl}</a> : NA],
        ]} />
      </Section>

      <Section title="Clicks & registrations">
        <DL rows={[
          ['Tracked link', <a href={op.referralUrl} className="text-accent hover:underline">{op.referralUrl}</a>],
          ['Clicks', String(op.clicksCount)],
          ['Registrations attributed', String(op.registrationsCount)],
        ]} />
        <p className="mt-2 text-[11px] text-muted-foreground">Clicks and registrations are real, tracked via the same redirect link used for every other acquisition opportunity — a click is never counted as a registration.</p>
      </Section>
    </Drawer>
  );
}
